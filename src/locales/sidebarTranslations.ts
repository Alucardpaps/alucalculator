export function getLocalizedNavTitle(groupId: string, lang: Language): string {
  const titles = SIDEBAR_GROUP_TITLES[groupId];
  if (!titles) return groupId.toUpperCase();
  return titles[lang] || titles.en;
}

export function getLocalizedNavItemLabel(
  item: { id: string; labelEn: string; labelTr: string },
  lang: Language,
): string {
  const custom = SIDEBAR_ITEM_LABELS[item.id];
  if (custom && custom[lang]) {
    return custom[lang]!;
  }
  if (lang === 'tr') return item.labelTr;
  return item.labelEn;
}
