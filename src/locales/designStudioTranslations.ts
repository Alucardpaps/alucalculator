export function getDesignKindLabel(kind: string, lang: Language): string {
  const custom = DESIGN_KIND_LABELS[kind];
  if (custom && custom[lang]) return custom[lang]!;
  if (custom && custom.en) return custom.en;
  return kind.replace('-', ' ');
}

