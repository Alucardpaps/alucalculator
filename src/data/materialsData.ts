    poissonsRatio: number;  // ν (dimensionless)
    shearModulus?: number;  // GPa (G)
    enduranceLimit?: number; // MPa (Se)
    thermalCond?: number;   // W/(m·K)
    thermalExp?: number;    // μm/(m·K) (α)
    specificHeat?: number;  // J/(kg·K)
    elecResist?: number;    // µΩ·cm
