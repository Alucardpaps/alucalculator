import type { FlowNode, FlowEdge } from '@/store/flowStore';
import type { FlowTemplate } from './types';

function node(
    id: string,
    x: number,
    y: number,
    schemaId: string,
    extra: Record<string, unknown> = {}
): FlowNode {
    return {
        id,
        type: 'engineering',
        position: { x, y },
        data: { type: 'engineering', schemaId, nodeVersion: '1.0.0', ...extra } as FlowNode['data'],
    };
}

function edge(
    id: string,
    source: string,
    sourceHandle: string,
    target: string,
    targetHandle: string,
    color = '#00e5ff'
): FlowEdge {
    return {
        id,
        source,
        sourceHandle,
        target,
        targetHandle,
        animated: true,
        style: { stroke: color, strokeWidth: 2 },
    };
}

