"""Generate src/styles/palette.css — re-points Tailwind's default palette to theme tokens.

Neutral families and the brand accent are expressed through theme tokens (so they
follow every theme automatically, including inversion in light themes). Other
chromatic families keep Tailwind's values in dark themes and are mirrored
(50<->950, 100<->900 ...) in light themes so text-emerald-400 etc. stay legible.
"""
import re, sys

theme_css = open(sys.argv[1]).read()
out_path = sys.argv[2]

vals = dict(re.findall(r"--color-([a-z]+-\d+):\s*([^;]+);", theme_css))
STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
NEUTRALS = ["slate", "gray", "zinc", "neutral", "stone"]
ACCENT_FAMILIES = ["cyan"]
CHROMA = sorted({k.split("-")[0] for k in vals} - set(NEUTRALS) - set(ACCENT_FAMILIES))

neutral_map = {
    950: "var(--bg-0)",
    900: "var(--bg-1)",
    800: "var(--bg-3)",
    700: "var(--line-strong)",
    600: "color-mix(in oklab, var(--muted) 65%, var(--line-strong))",
    500: "var(--muted)",
    400: "var(--alu-dim)",
    300: "var(--alu)",
    200: "color-mix(in oklab, var(--ink) 70%, var(--alu))",
    100: "color-mix(in oklab, var(--ink) 88%, var(--alu))",
    50: "var(--ink)",
}
accent_map = {
    950: "color-mix(in oklab, var(--cyan) 10%, var(--bg-0))",
    900: "color-mix(in oklab, var(--cyan) 20%, var(--bg-0))",
    800: "color-mix(in oklab, var(--cyan) 34%, var(--bg-0))",
    700: "var(--cyan-dim)",
    600: "color-mix(in oklab, var(--cyan) 70%, var(--cyan-dim))",
    500: "var(--cyan)",
    400: "var(--cyan)",
    300: "color-mix(in oklab, var(--cyan) 78%, var(--ink))",
    200: "color-mix(in oklab, var(--cyan) 55%, var(--ink))",
    100: "color-mix(in oklab, var(--cyan) 32%, var(--ink))",
    50: "color-mix(in oklab, var(--cyan) 16%, var(--ink))",
}

lines = [
    "/* AUTO-GENERATED by scripts/theme/gen_palette.py — do not edit by hand. */",
    "/* Tailwind palette → theme tokens. Lets dark-authored classes work in every theme. */",
    "",
    "@theme {",
    "  --color-white: var(--ink);",
    "  --color-black: var(--bg-0);",
]
for fam in NEUTRALS:
    for s in STEPS:
        lines.append(f"  --color-{fam}-{s}: {neutral_map[s]};")
for fam in ACCENT_FAMILIES:
    for s in STEPS:
        lines.append(f"  --color-{fam}-{s}: {accent_map[s]};")
lines.append("}")
lines.append("")
lines.append("/* Light themes: mirror chromatic scales so bright-on-dark shades become dark-on-light. */")
lines.append(':root[data-theme="light"],')
lines.append(':root[data-theme="paper"] {')
for fam in CHROMA:
    for s in STEPS:
        mirror = {50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 600, 600: 500, 700: 300, 800: 200, 900: 100, 950: 50}[s]
        v = vals.get(f"{fam}-{mirror}")
        if v:
            lines.append(f"  --color-{fam}-{s}: {v.strip()};")
lines.append("}")
lines.append("")
lines.append("/* Islands that must keep the literal Tailwind palette (printable reports, brand art). */")
lines.append(".palette-literal, .palette-literal * {")
lines.append("  --color-white: #fff;")
lines.append("  --color-black: #000;")
for fam in NEUTRALS + ACCENT_FAMILIES + CHROMA:
    for s in STEPS:
        v = vals.get(f"{fam}-{s}")
        if v:
            lines.append(f"  --color-{fam}-{s}: {v.strip()};")
lines.append("}")
open(out_path, "w").write("\n".join(lines) + "\n")
print("families:", len(NEUTRALS) + len(ACCENT_FAMILIES) + len(CHROMA), "chroma:", CHROMA)
